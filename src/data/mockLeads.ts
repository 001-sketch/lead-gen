export function getProcessedSeedLeads(): Lead[] {
  return RAW_SEEDS.map((seed) => {
    const websiteAnalysis = !seed.hasWebsite
      ? calculateWebsiteOpportunity(seed.name, seed.category, seed.rating, seed.userRatingCount, seed.city)
      : undefined;

    const adsAnalysis = calculateAdsOpportunity(
      seed.name,
      seed.category,
      seed.rating,
      seed.userRatingCount,
      seed.city,
      seed.hasWebsite
    );

    let leadType: Lead['leadType'] = 'both';
    if (!seed.hasWebsite && adsAnalysis.opportunityScore < 70) {
      leadType = 'no_website';
    } else if (seed.hasWebsite && adsAnalysis.opportunityScore >= 60) {
      leadType = 'ads_opportunity';
    }

    return {
      id: seed.id,
      name: seed.name,
      category: seed.category,
      categoryLabel: seed.categoryLabel,
      address: seed.address,
      city: seed.city,
      state: seed.state,
      country: seed.country,
      location: seed.location,
      rating: seed.rating,
      userRatingCount: seed.userRatingCount,
      hasWebsite: seed.hasWebsite,
      websiteUrl: seed.websiteUrl || null,
      phoneNumber: seed.phoneNumber,
      googleMapsUrl: seed.googleMapsUrl,
      primaryType: seed.primaryType,
      leadType,
      websiteAnalysis,
      adsAnalysis,
      pipelineStatus: 'new',
    };
  });
}
